/** 没有任何笔记时创建示例笔记（先建技巧，再建欢迎，让欢迎笔记排在最上面） */
async function createWelcomeNotes(noteService) {
  const notesResult = await noteService.getNotes({ limit: 1 })
  const empty = notesResult?.success && notesResult.data?.notes?.length === 0
  if (!empty) return false
  await noteService.createNote({ title: TIPS_TITLE, content: tipsContent, tags: ['Flota', '技巧'] })
  await noteService.createNote({ title: WELCOME_TITLE, content: welcomeContent, tags: ['欢迎', 'Flota'] })
  return true
}

module.exports = { createWelcomeNotes, WELCOME_TITLE, TIPS_TITLE }
